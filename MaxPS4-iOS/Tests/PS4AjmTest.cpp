int main() {
    GuestELF image;
    auto elf = guest_test::elf(40, 2, true);
    guest_test::put(elf, 8192, 160, 8);
    assert(image.load(elf.data(), elf.size(), 6) == 0);
    PS4GuestMemory memory(image);
    PS4Ajm ajm(memory);
    const uint64_t input = 0x10000, output = 0x10600, sideband = 0x11000, batch = 0x11100, ids = 0x11200;
    assert(memory.write(input, mono_mp3, sizeof mono_mp3));
    assert(ajm.instance_create(0, 1u << 3, ids) == 0); // MP3, one channel, S16
    uint32_t instance = 0;
    assert(memory.read(ids, &instance, 4));
    const uint64_t stream = 1ull << 47;
    struct Stream { int32_t result, internal, consumed, written; uint64_t total; } s{};
    // One mono frame of S16 is 1152 x 2 bytes: less than the stereo worst case.
    const uint64_t end = ajm.job_run(batch, instance, stream, input, sizeof mono_mp3, output, 1152 * 2, sideband, sizeof s);
    assert(end == batch + 56);
    assert(ajm.batch_start(batch, end - batch, ids + 4) == 0);
    assert(memory.read(sideband, &s, sizeof s));
    assert(!(s.result & PS4Ajm::result_not_enough_room));
    assert(s.written == 1152 * 2 && s.consumed >= 192 && s.total == 1152);
    // Too small for even one frame: nothing consumed, the room reported.
    const uint64_t end2 = ajm.job_run(batch, instance, stream, input + s.consumed, sizeof mono_mp3 - s.consumed, output, 1000, sideband, sizeof s);
    assert(ajm.batch_start(batch, end2 - batch, ids + 4) == 0);
    assert(memory.read(sideband, &s, sizeof s));
    assert((s.result & PS4Ajm::result_not_enough_room) && s.written == 0 && s.consumed == 0);
    const std::string note = ajm.note();
    assert(note.find("2 lancements, 1 sans trame (1 place insuffisante") == 0);
    std::puts("PASS AJM MP3: mono frame into a one-frame buffer, room reported, run outcomes");
}
